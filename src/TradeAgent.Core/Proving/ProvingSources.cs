using TradeAgent.Core.Data;

namespace TradeAgent.Core.Proving;

/// <summary>
/// THE PROVING GROUND'S OWN TAPE ROW (<c>U-proving-ground-a</c> item 3): the source a synthetic market's series are
/// recorded under, so a synthetic datum never wears a real vendor's id (SIM-001, EVID-001).
///
/// <para><b>A separate list, never one of <see cref="TapeSourceCatalog.Shipped"/></b>: the frozen live rule, the
/// collectors and a real home's feature parse read that list and never this one. Only a store or a reader of kind
/// <see cref="HomeKind.Proving"/> consults it (<see cref="TapeSourceCatalog.LiveRule"/>,
/// <see cref="TapeSourceCatalog.Readable"/>) — so in a real home a program naming it is refused at parse, and a row
/// recorded under it, from anywhere, can only be <c>O-ARCH</c>. No collector ever asks its address: it is under the
/// reserved <c>.invalid</c> name, which resolves nowhere.</para>
/// </summary>
public static class ProvingSources
{
    /// <summary>The proving ground's synthetic source.</summary>
    public const string Synthetic = "proving-synthetic";

    /// <summary>Its origin: a reserved name that resolves nowhere, so nothing is ever fetched from it.</summary>
    public const string Origin = "https://synthetic.invalid";

    /// <summary>The one series a first-cut market writes: a signal per instrument, one reading an hour.</summary>
    public const string Signal = "signal";

    /// <summary>The field of a signal reading a feature reads: a plain decimal.</summary>
    public const string ValueField = "value";

    /// <summary>The synthetic instruments a proving market may name. Not any venue's symbols.</summary>
    public static readonly IReadOnlyList<string> Subjects = ["SYNA", "SYNB", "SYNC", "SYND"];

    /// <summary>How often a signal is published: once an hour, at ten past.</summary>
    public const int CadenceSeconds = 3600;

    /// <summary>How late after its source time a signal is first seen: the declared delay, two seconds.</summary>
    public static readonly TimeSpan Delay = TimeSpan.FromSeconds(2);

    /// <summary>
    /// THE SERIES A PROVING MARKET MAY WRITE, BY SHAPE: each its own field names, publication cadence and minute, so a
    /// reading of one is never mistaken for a reading of another.
    /// </summary>
    public static readonly IReadOnlyList<SyntheticSeriesShape> Shapes =
    [
        new(Signal, "time", ValueField, 60, SyntheticMarket.SignalMinute, Family: false,
            "the proving ground's bare signal: a plain decimal an hour, shaped like no real family, so no playbook names it")
    ];

    /// <summary>The shape of series <paramref name="id"/>, or null when the proving ground writes none by that name.</summary>
    public static SyntheticSeriesShape? Shape(string? id) => Shapes.FirstOrDefault(s => string.Equals(s.Id, id, StringComparison.Ordinal));

    /// <summary>The proving-only rows, a fresh copy on every call.</summary>
    public static List<TapeSourceEntry> Rows() =>
    [
        new()
        {
            Id = Synthetic,
            DisplayName = "TradeAgent proving ground, synthetic series",
            BaseUrl = Origin,
            CadenceSeconds = CadenceSeconds,
            PerSymbol = false,
            Parser = TapeSourceCatalog.JsonParser,
            Series = [.. Shapes.Select(s => new TapeSeriesEntry { Id = s.Id, UrlShape = "{base}/" + s.Id, TimeField = s.TimeField, SymbolField = "symbol" })],
            Subjects = [.. Subjects],
            PublicationDelay = Delay,
            Terms = "Synthetic by construction: generated by TradeAgent's proving ground from hand-set constants and a "
                    + "seed, never fitted to, estimated from or seeded by any real tape, dataset or ledger.",
            Measured = "never measured: nothing is fetched from this row; its readings are written by the proving ground's generator"
        }
    ];
}

/// <summary>
/// ONE SERIES' SHAPE (<c>U-proving-ground-b</c>): its id, the payload's time and value fields, how often a reading is
/// published and at which minute, and whether it is shaped like a real family's — the only series an edge INSIDE doctrine
/// may ride.
/// </summary>
/// <param name="Id">The series' id on the proving row.</param>
/// <param name="TimeField">The payload's field holding the source time, in Unix milliseconds.</param>
/// <param name="ValueField">The payload's field a feature reads: a plain decimal.</param>
/// <param name="CadenceMinutes">Minutes between readings.</param>
/// <param name="MinuteOffset">Minutes after the market's start, and after every cadence, a reading is stamped at.</param>
/// <param name="Family">Whether the series is shaped like a real family's payload.</param>
/// <param name="Words">What the series is, in words, for the manifest.</param>
public sealed record SyntheticSeriesShape(
    string Id, string TimeField, string ValueField, int CadenceMinutes, int MinuteOffset, bool Family, string Words)
{
    /// <summary>How many readings a market of <paramref name="days"/> days holds.</summary>
    public int Count(int days) => (days * 1440 - MinuteOffset + CadenceMinutes - 1) / CadenceMinutes;

    /// <summary>Reading <paramref name="k"/>'s source time, in minutes after the market's start.</summary>
    public long SourceMinute(int k) => (long)k * CadenceMinutes + MinuteOffset;
}
